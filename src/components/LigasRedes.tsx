export type RedesDelPerfil = Partial<Record<ClaveRed, string | null>>;

export function LigasRedes({ redes }: { redes: RedesDelPerfil }) {
  const puestas = REDES.filter((red) => redes[red.clave]);

  if (puestas.length === 0) return null;

  return (
    <div className="flex flex-wrap gap-2">
      {puestas.map((red) => {
        const direccion = redes[red.clave] as string;

        return (
          <a
            key={red.clave}
            href={direccion}
            target="_blank"
            rel="noopener noreferrer nofollow"
            title={`${red.nombre}: ${comoSeLee(red.clave, direccion)}`}
            className="inline-flex min-h-[40px] items-center gap-2 rounded-suave border border-marino/20 bg-white px-3 text-sm font-medium text-marino transition-colors hover:border-marino/45 hover:bg-marino-tenue"
          >
            <svg viewBox="0 0 24 24" className="size-4 fill-current" aria-hidden="true">
              <path d={iconos[red.clave]} />
            </svg>
            {red.nombre}
          </a>
        );
      })}
    </div>
  );
}
